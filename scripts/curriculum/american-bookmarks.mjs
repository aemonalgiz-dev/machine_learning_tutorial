export function applyAmericanBookmarks(lessons, depthSupplements = {}) {
  for (const lesson of lessons) {
    const saved = lessonBookmarks[lesson.id];
    if (!saved) continue;
    if (saved.openingId) lesson.openingId = saved.openingId;
    for (const part of saved.parts ?? []) lesson.parts[part.index].id = part.id;
    for (const checkpoint of saved.checkpoints ?? []) lesson.checkpoints[checkpoint.index].id = checkpoint.id;
  }
  for (const [id, saved] of Object.entries(supplementBookmarks)) {
    const supplement = depthSupplements[id];
    if (!supplement) continue;
    for (const part of saved.parts ?? []) supplement.parts[part.index].id = part.id;
    if (saved.checkpointId) supplement.checkpoint.id = saved.checkpointId;
  }
}
