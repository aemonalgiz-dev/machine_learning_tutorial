const words = new RegExp("\\b(" + Object.keys(spellings).sort((a, b) => b.length - a.length).join("|") + ")\\b", "gi");

export function americanEnglish(text: string): string {
  return text.split(/(```[\s\S]*?```|`[^`]*`)/g).map((part, index) => index % 2 ? part : part.replace(words, word => {
    const value = spellings[word.toLowerCase()];
    return word === word.toUpperCase() ? value.toUpperCase() : word[0] === word[0].toUpperCase() ? value[0].toUpperCase() + value.slice(1) : value;
  })).join("");
}
